import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { relative, resolve, sep } from 'node:path';

const dist = resolve('dist');
const serviceWorkerPath = resolve(dist, 'service-worker.js');

async function listFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const path = resolve(directory, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  }));
  return nested.flat();
}

const files = (await listFiles(dist))
  .filter((path) => path !== serviceWorkerPath)
  .sort((a, b) => a.localeCompare(b));
const publicPaths = files.map((path) => `./${relative(dist, path).split(sep).join('/')}`);
const versionHash = createHash('sha256');
versionHash.update('worker-strategy:network-first-navigation-v4-ignore-vary');

for (const path of files) {
  versionHash.update(relative(dist, path));
  versionHash.update(await readFile(path));
}

const version = versionHash.digest('hex').slice(0, 16);
const source = `/* Generated by scripts/generate-service-worker.mjs. */
const CACHE_PREFIX = 'allneeds-v2-shell-';
const CACHE_NAME = CACHE_PREFIX + '${version}';
const PRECACHE_PATHS = ${JSON.stringify(publicPaths, null, 2)};
const scopeUrl = new URL(self.registration.scope);
const fallbackUrl = new URL('./index.html', scopeUrl).href;
const apiPath = new URL('./allneeds-api', scopeUrl).pathname;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    const requests = PRECACHE_PATHS.map((path) => new Request(
      new URL(path, scopeUrl),
      { cache: 'reload' },
    ));
    await cache.addAll(requests);
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== scopeUrl.origin || url.pathname.startsWith(apiPath)) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        return await fetch(request);
      } catch (error) {
        const cache = await caches.open(CACHE_NAME);
        const shell = await cache.match(fallbackUrl, { ignoreVary: true });
        if (shell) return shell;
        throw error;
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(request, { ignoreVary: true });
    if (cached) return cached;
    return fetch(request);
  })());
});
`;

await writeFile(serviceWorkerPath, source);
console.log(`Created dist/service-worker.js with ${publicPaths.length} public assets (${version}).`);
